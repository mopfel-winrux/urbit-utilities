#!/usr/bin/env python3
"""Compile ../catalog.json into hub/desk/lib/utilities-catalog.hoon, and list
the icons in hub/desk/web/icons/ in web/icons/index.json (so the UI knows which
<desk>.svg/.png exist without probing and causing 404s).

usage: python3 hub/gen-catalog.py      (then |commit %utilities)
The JSON is embedded verbatim (compact, ASCII) as a cord and parsed by the
agent at request time, so unknown fields pass through to the API untouched.
"""
import json, os, sys

HUB = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(os.path.dirname(HUB), 'catalog.json')
out = os.path.join(HUB, 'desk', 'lib', 'utilities-catalog.hoon')
apps = json.load(open(src))
assert isinstance(apps, list), 'catalog.json must be a list'
for a in apps:
    for k in ('desk', 'title', 'info', 'category', 'tier'):
        assert k in a, f'{a.get("desk")}: missing {k}'
    d = a['desk']
    assert d and d[0].isalpha() and all(c.islower() or c.isdigit() or c == '-' for c in d), f'bad desk {d}'
raw = json.dumps(apps, separators=(',', ':'), ensure_ascii=True)
cord = raw.replace('\\', '\\\\').replace("'", "\\'")
with open(out, 'w') as fh:
    fh.write('::  GENERATED by hub/gen-catalog.py from catalog.json; do not edit\n::\n')
    fh.write('|%\n++  raw  ^-  @t\n  \'' + cord + '\'\n--\n')
print(f'{out}: {len(apps)} apps')

icons = os.path.join(HUB, 'desk', 'web', 'icons')
os.makedirs(icons, exist_ok=True)
have = sorted(f for f in os.listdir(icons)
              if f.rsplit('.', 1)[-1] in ('svg', 'png') and f.rsplit('.', 1)[0])
with open(os.path.join(icons, 'index.json'), 'w') as fh:
    json.dump(have, fh)
print(f'icons: {len(have)}')
