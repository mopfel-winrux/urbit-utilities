// Build an offline Iconify bundle for every icon name used in src/, so
// @iconify/react never calls api.iconify.design at runtime.
// usage: node offline-icons.mjs <upstream-dir> <iconify-json-dir>
import fs from 'fs';
import path from 'path';

const [, , up, jsonDir] = process.argv;
const files = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(tsx?|jsx?)$/.test(e.name)) files.push(p);
  }
})(path.join(up, 'src'));

const wanted = new Map(); // prefix -> Set(names)
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8');
  for (const m of src.matchAll(/['"`]([a-z0-9]+(?:-[a-z0-9]+)*):([a-z0-9]+(?:-[a-z0-9]+)*)['"`]/g)) {
    const [, prefix, name] = m;
    if (!fs.existsSync(path.join(jsonDir, `${prefix}.json`))) continue;
    if (!wanted.has(prefix)) wanted.set(prefix, new Set());
    wanted.get(prefix).add(name);
  }
}

const collections = [];
let count = 0;
const missing = [];
for (const [prefix, names] of wanted) {
  const set = JSON.parse(fs.readFileSync(path.join(jsonDir, `${prefix}.json`), 'utf8'));
  const out = { prefix, icons: {}, aliases: {} };
  for (const k of ['width', 'height', 'left', 'top']) if (k in set) out[k] = set[k];
  const add = (name, depth = 0) => {
    if (set.icons[name]) { out.icons[name] = set.icons[name]; return true; }
    const alias = set.aliases?.[name];
    if (alias && depth < 5 && add(alias.parent, depth + 1)) { out.aliases[name] = alias; return true; }
    return false;
  };
  for (const n of names) {
    if (add(n)) count++;
    else if (/[a-z]/.test(n)) missing.push(`${prefix}:${n}`);
  }
  collections.push(out);
}
const target = path.join(up, 'src', 'iconify-offline-data.ts');
fs.writeFileSync(target, '// generated by satellites/omni-tools/scripts/offline-icons.mjs\n// eslint-disable-next-line @typescript-eslint/no-explicit-any\nconst data: any[] = ' + JSON.stringify(collections) + ';\nexport default data;\n');
console.log(`offline icons: ${count} icons from ${collections.length} sets -> ${target}`);
if (missing.length) console.log('not found (ignored, probably not icons):', missing.join(' '));
